/**
 * 入场动画的弹簧参数。
 *
 * 阻尼必须 ≥ 2√stiffness（临界阻尼），否则弹簧会**过冲** ——
 * 元素先冲过目标位置、再荡回来、再冲过去，观感就是「来回抽动」。
 *
 * 本项目原先在各处手写成 `damping: 16~20`，实际阻尼比 ζ = d/(2√k)
 * 只有 0.52~0.75，于是全项目的入场动画都在抖。
 * 这里统一按 ζ=1 推导，不再手调：k=150→25、200→29、250→32、300→35。
 *
 * 不适用于交互类动画（鼠标跟随、按压反馈）—— 那些地方的回弹是刻意的
 * 手感设计，见 TiltCard 的 3D 跟随弹簧。
 */
export function entrySpring(stiffness: number) {
  return {
    type: 'spring' as const,
    stiffness,
    damping: Math.ceil(2 * Math.sqrt(stiffness)),
  };
}

/**
 * 切换类动画的弹簧：**刻意欠阻尼，要的就是那一下回弹**。
 *
 * ⚠️ 跟上面的 entrySpring 不一样是故意的，别"顺手统一"成临界阻尼 ——
 * 入场动画过冲会被看成抖动（见上），而这一条用在**用户主动操作引发的形变**上：
 * 点一下页签、卡片跟着弹一下，回弹本身就是操作反馈。把阻尼提到临界值，
 * 切换会变得很"木"，用户要的「Q弹」就没了。
 *
 * ζ = d/(2√k) = 16/(2√160) ≈ 0.63 → 过冲约 7.7%。第二次过冲只剩 0.6%，
 * 所以是「回弹一次即停」，不会来回荡。
 * 按 143px 的卡片高度差算，冲过头 11px —— 看得出来，但不至于轻浮。
 *
 * ⚠️ 这对数字是**用户调出来的**，别按"看着不够快"往回加：
 * 一开始是 k=300/d=22（ζ 一样，只是快 27%），用户反馈「弹的有点快」。
 * 调慢只动了 ω=√k，阻尼比原样保留 —— 手感形状没变，只是整体拉长。
 * 要再慢就继续按 ζ≈0.63 同比例降 k 与 d（d = 2ζ√k），别只降 k，
 * 那只降频率不改阻尼比会连带把回弹也改了。
 */
export const toggleSpring = {
  type: 'spring' as const,
  stiffness: 160,
  damping: 16,
};
