import type { Transition } from 'framer-motion';

/**
 * 入场动画的弹簧参数。
 *
 * 阻尼必须 ≥ 2√stiffness（临界阻尼），否则弹簧会**过冲** ——
 * 元素先冲过目标位置、再荡回来、再冲过去，观感就是「来回抽动」。
 *
 * 本项目原先在各处手写成 `damping: 16~20`，实际阻尼比 ζ = d/(2√k)
 * 只有 0.52~0.75，于是全项目的入场动画都在抖。
 * 这里统一按 ζ=1 推导，不再手调：k=150→25、200→29、250→32、300→35。
 *
 * 不适用于交互类动画（鼠标跟随、按压反馈）—— 那些地方的回弹是刻意的
 * 手感设计，见 TiltCard 的 3D 跟随弹簧。
 */
export function entrySpring(stiffness: number) {
  return {
    type: 'spring' as const,
    stiffness,
    damping: Math.ceil(2 * Math.sqrt(stiffness)),
  };
}

/**
 * 面板/页签切换时的形变过渡。**这两组数字是量出来的，别凭手感改。**
 *
 * 前后试了四轮，每轮用户的原话都记在这儿：
 *   k=300/d=22 弹簧        →「弹的有点快」
 *   k=160/d=16 弹簧        →「太卡」
 *   [0.22,1,0.36,1] 0.35s  →「停的时候一顿一顿」
 *   ↓ 就是下面这组
 *
 * ⚠️「一顿一顿」**不是性能问题**：实测帧间隔全程 16~18ms，一帧都没掉。
 * 是上面那条曲线太前倾 —— 一帧先冲 30px，最后 100ms 每帧只剩零点几像素，
 * 而浏览器把高度吸附到整像素，画面就在 307/307/306/306 之间**蹦格子**。
 *
 * 所以判据是「尾部龟速时长」= 每帧位移 <0.5px 持续了多少毫秒（看着像已经停了）。
 * 按 143px 的卡片高度差实算：
 *   [0.22,1,0.36,1] 0.35s  → 尾巴 100ms   ← 就是它
 *   [0.4,0,0.2,1]   0.35s  → 尾巴  17ms
 *   [0.4,0,0.2,1]   0.28s  → 尾巴   0ms   ← 用这组，起步也不拖
 *   [0.4,0,0.2,1]   0.30s  → 尾巴  17ms（再长一点尾巴就回来了）
 * 峰值帧步 22px，比原来那条的 29px 还平缓。
 */
export const toggleTransition: Transition = {
  type: 'tween',
  duration: 0.28,
  ease: [0.4, 0, 0.2, 1],
};
