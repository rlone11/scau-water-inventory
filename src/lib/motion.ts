import type { Transition } from 'framer-motion';

/**
 * 入场动画的弹簧参数。
 *
 * 阻尼必须 ≥ 2√stiffness（临界阻尼），否则弹簧会**过冲** ——
 * 元素先冲过目标位置、再荡回来、再冲过去，观感就是「来回抽动」。
 *
 * 本项目原先在各处手写成 `damping: 16~20`，实际阻尼比 ζ = d/(2√k)
 * 只有 0.52~0.75，于是全项目的入场动画都在抖。
 * 这里统一按 ζ=1 推导，不再手调：k=150→25、200→29、250→32、300→35。
 *
 * 不适用于交互类动画（鼠标跟随、按压反馈）—— 那些地方的回弹是刻意的
 * 手感设计，见 TiltCard 的 3D 跟随弹簧。
 */
export function entrySpring(stiffness: number) {
  return {
    type: 'spring' as const,
    stiffness,
    damping: Math.ceil(2 * Math.sqrt(stiffness)),
  };
}

/**
 * 面板/页签切换时的形变过渡：**匀速拉伸到位，不回弹**。
 *
 * ⚠️ 别改回弹簧，这条路趟过了（2026-09-21）：
 *   - 先试 k=300/d=22（ζ≈0.63、过冲 7.6%）→ 用户「弹的有点快」
 *   - 调慢到 k=160/d=16（同阻尼比，峰值时刻 267→320ms）→ 用户「太卡」
 *
 * 那次「卡」不是错觉，也不是机器不行：**动画 height 每帧都要重新布局整张
 * 卡片**（卡片里还嵌着钉钉的 iframe），弹簧收尾那段等于白白多跑几十帧布局。
 * 所以这里两个决定都是从代价出发的：
 *   1. 不做回弹 —— 过冲那段纯属白花
 *   2. 时长压到 0.35s（弹簧的停稳时刻在 0.55s 左右）
 *
 * 曲线跟登录页入场用的是同一条 [0.22, 1, 0.36, 1]（起步快、收尾长而稳），
 * 这是本项目「丝滑」的统一手感。
 */
export const toggleTransition: Transition = {
  type: 'tween',
  duration: 0.35,
  ease: [0.22, 1, 0.36, 1],
};
